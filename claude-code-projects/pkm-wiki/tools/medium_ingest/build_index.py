#!/usr/bin/env python3
"""
build_index.py — Generate an HTML index of every Medium article ever ingested.

Source of truth: raw/.medium_cache.json (canonical URL -> {path, processed_at}).
Cross-references each cached filename against wiki page `changes:` frontmatter
to show where the article landed in the wiki, if it has been ingested yet.

Usage:
    python tools/medium_ingest/build_index.py

Writes: tools/medium_ingest/ingested-index.html
"""

import html
import json
import re
from datetime import datetime
from pathlib import Path

_HERE = Path(__file__).resolve().parent


def find_config_dir() -> Path:
    for root in [_HERE, _HERE.parent, _HERE.parent.parent, Path.home()]:
        for cfg in root.rglob("wiki-config.md"):
            return cfg.parent
    raise FileNotFoundError("Could not locate wiki-config.md")


def parse_config(cfg_path: Path) -> dict:
    text = cfg_path.read_text(encoding="utf-8")
    fm = re.search(r"^---\n(.*?)\n---", text, re.S).group(1)
    wiki_root = re.search(r"^wiki_root:\s*(.+)$", fm, re.M).group(1).strip()
    staging_root = re.search(r"^staging_root:\s*(.+)$", fm, re.M).group(1).strip()
    return {"wiki_root": Path(wiki_root), "staging_root": Path(staging_root)}


def load_cache(staging_root: Path) -> dict:
    cache_path = staging_root / "raw" / ".medium_cache.json"
    if not cache_path.exists():
        return {}
    return json.loads(cache_path.read_text(encoding="utf-8"))


def build_filename_to_wikipages(wiki_root: Path) -> dict:
    """Map ingested source filename -> list of wiki page relative paths that cite it."""
    mapping: dict[str, list[Path]] = {}
    for md in wiki_root.rglob("*.md"):
        try:
            text = md.read_text(encoding="utf-8")
        except OSError:
            continue
        for m in re.finditer(r"ingested/[\w\-./]+?/([\w\-.]+\.md)", text):
            filename = m.group(1)
            mapping.setdefault(filename, [])
            rel = md.relative_to(wiki_root)
            if rel not in mapping[filename]:
                mapping[filename].append(rel)
    return mapping


def canonical(url: str) -> str:
    return url.split("?")[0].rstrip("/")


def render_html(rows: list[dict]) -> str:
    def esc(s: str) -> str:
        return html.escape(s, quote=True)

    body_rows = []
    for r in rows:
        wiki_cell = (
            "<br>".join(f'<span class="wp">{esc(str(p))}</span>' for p in r["wiki_pages"])
            if r["wiki_pages"]
            else '<span class="pending">not yet ingested to wiki</span>'
        )
        body_rows.append(f"""
        <tr>
          <td class="date">{esc(r['processed_at'][:10])}</td>
          <td><a href="{esc(r['url'])}" target="_blank" rel="noopener">{esc(r['url'])}</a></td>
          <td>{wiki_cell}</td>
        </tr>""")

    return f"""<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>Medium Articles Ingested</title>
<style>
  :root {{ color-scheme: light dark; }}
  body {{ font-family: -apple-system, Segoe UI, sans-serif; max-width: 1100px; margin: 2rem auto; padding: 0 1rem; }}
  h1 {{ font-size: 1.4rem; }}
  .meta {{ color: #888; font-size: 0.85rem; margin-bottom: 1.5rem; }}
  table {{ border-collapse: collapse; width: 100%; }}
  th, td {{ text-align: left; padding: 0.5rem 0.75rem; border-bottom: 1px solid #ddd; vertical-align: top; font-size: 0.9rem; }}
  th {{ border-bottom: 2px solid #999; }}
  .date {{ white-space: nowrap; color: #666; }}
  .wp {{ font-family: monospace; font-size: 0.82rem; }}
  .pending {{ color: #b8860b; font-style: italic; }}
  a {{ color: #0969da; text-decoration: none; word-break: break-all; }}
  a:hover {{ text-decoration: underline; }}
</style>
</head>
<body>
<h1>Medium Articles Ingested</h1>
<div class="meta">{len(rows)} unique article(s) &middot; regenerate with <code>python tools/medium_ingest/build_index.py</code></div>
<table>
<thead><tr><th>Date</th><th>Medium URL</th><th>Wiki page</th></tr></thead>
<tbody>{''.join(body_rows)}</tbody>
</table>
</body>
</html>
"""


def render_markdown(rows: list[dict], today: str) -> str:
    lines = [
        "---",
        "title: Medium Articles Ingested",
        "version: 1.0",
        f"date: {today}",
        "changes: Auto-generated by tools/medium_ingest/build_index.py from raw/.medium_cache.json",
        "---",
        "",
        f"Standing cross-reference of every Medium article ingested via `tools/medium_ingest`, "
        f"mapped to the wiki page it produced. Regenerate with "
        "`python3 tools/medium_ingest/build_index.py` (run automatically by `/wiki-ingest` "
        "after any Medium-sourced batch).",
        "",
        f"{len(rows)} unique article(s).",
        "",
        "| Date | Medium URL | Wiki page |",
        "|---|---|---|",
    ]
    for r in rows:
        wiki_cell = (
            "<br>".join(str(p) for p in r["wiki_pages"])
            if r["wiki_pages"]
            else "_not yet ingested to wiki_"
        )
        lines.append(f"| {r['processed_at'][:10]} | <{r['url']}> | {wiki_cell} |")
    lines.append("")
    return "\n".join(lines)


def main():
    cfg_dir = find_config_dir()
    cfg = parse_config(cfg_dir / "wiki-config.md")
    wiki_root, staging_root = cfg["wiki_root"], cfg["staging_root"]

    cache = load_cache(staging_root)
    wiki_map = build_filename_to_wikipages(wiki_root)

    rows = []
    seen = set()
    for url, meta in cache.items():
        c = canonical(url)
        if c in seen:
            continue
        seen.add(c)
        filename = meta.get("path", "")
        rows.append({
            "url": url,
            "processed_at": meta.get("processed_at", ""),
            "wiki_pages": wiki_map.get(filename, []),
        })
    rows.sort(key=lambda r: r["processed_at"])

    out_path = _HERE / "ingested-index.html"
    out_path.write_text(render_html(rows), encoding="utf-8")

    today = datetime.now().strftime("%Y-%m-%d")
    vault_path = wiki_root / "meta" / "Medium Articles Ingested.md"
    vault_path.parent.mkdir(parents=True, exist_ok=True)
    vault_path.write_text(render_markdown(rows, today), encoding="utf-8")

    print(f"Wrote {len(rows)} unique article(s) to {out_path} and {vault_path}")


if __name__ == "__main__":
    main()
